import { build } from "esbuild";
import { writeFile } from "node:fs/promises";
const result = await build({
  entryPoints: ["scripts/movement.js"],
  bundle: true,
  minify: true,
  format: "iife",
  write: false,
});
const html = `<!doctype html><html><head><meta name="viewport" content="width=device-width,initial-scale=1"><style>html,body{margin:0;height:100%;overflow:hidden}canvas{touch-action:none}</style></head><body><script>window.MOTION="__MOTION__";</script><script>${result.outputFiles[0].text.replaceAll("</script", "<\\/script")}</script></body></html>`;
await writeFile(
  "src/components/movement-html.ts",
  `// Generated by npm run movement. Includes Three.js (MIT).\nexport const movementHTML = ${JSON.stringify(html)};\n`,
);
