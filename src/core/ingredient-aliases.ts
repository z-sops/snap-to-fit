/**
 * The ingredient alias foundation.
 *
 * A recipe addresses its ingredients by a USDA number today, and every one
 * of those numbers is persisted, in one place or another, by the recipe
 * library. That is the coupling this module exists to break, in stages.
 *
 * **This is a foundation, not a replacement.** Nothing in the app calls it
 * yet. The recipe engine still resolves ingredients exactly as it always
 * has, and the shipped catalogue is untouched. What is here is the registry,
 * the validation that keeps it honest, and the resolution contract that
 * says plainly what happened when an ingredient was looked up.
 *
 * The contract is deliberately blunt, because the failure it exists to
 * prevent is a food quietly changing its meaning:
 *
 *   resolved    the ingredient was found in the market that was asked for.
 *   fallback    the ingredient was found, but in another market. The result
 *               says which one, and the caller has to label it.
 *   incomplete  part of a composition could not be resolved. The composition
 *               is **not** a complete recipe and must not be shown as one.
 *   unavailable the ingredient could not be resolved at all.
 *
 * A missing ingredient never becomes a zero, and never becomes a different
 * food.
 */

// The registry, as generated by `scripts/build-ingredient-aliases.ts`.
export interface AliasEntry {
  /** The stable canonical key, `ingredient:<slug>`. */
  key: string;
  /** The name the app shows for it. */
  name: string;
  /**
   * The identifier for each market, by market code. A market that is not
   * listed has no approved equivalent in the registry, and saying so is
   * better than guessing.
   */
  ids: Record<string, string>;
  /**
   * The date each mapping was reviewed, by market.
   *
   * **A mapping without a review date is not a mapping.** It is an arbitrary
   * string, and the resolution refuses it. This is what separates a reviewed
   * mapping from a string that was typed into a registry by hand.
   *
   * A review date is a **marker that a review happened**. It is not, by
   * itself, evidence of nutritional equivalence, and nothing in the app may
   * describe it as such.
   */
  reviewed?: Record<string, string>;
  /**
   * The evidence behind each mapping that is not the default market's, by
   * market.
   *
   * **A mapping to another market needs evidence, not just a date.** The
   * evidence is what a reviewer read: the two records' identity, the basis
   * they are compared on, and the nutrients that differ. Without it the
   * mapping is refused, whatever date it carries.
   */
  evidence?: Record<string, string>;
  /**
   * An optional alias of another key. The alias resolves to whatever that key
   * resolves to. A chain that loops is a validation error, not a lookup that
   * runs for ever.
   */
  alias_of?: string;
}

export interface NotApproved {
  /** The identifier that was reviewed and not approved. */
  id: string;
  /** Why it was not approved. */
  reason: string;
}

export interface AliasRegistry {
  /** The version of the format. */
  version: number;
  /** The market used when a market has no mapping of its own. */
  default_market: string;
  /** How the registry was produced. */
  generated_by: string;
  /** The ingredients, in a deterministic order. */
  ingredients: AliasEntry[];
  /** Identifiers that were reviewed and are not approved for use. */
  not_approved: NotApproved[];
}

/** The market a lookup was asked for, and the one it ended at. */
export type Market = string;

/** How a lookup ended. */
export type ResolutionOutcome = "resolved" | "fallback" | "incomplete" | "unavailable";

/** Where an identifier came from. */
export type IdentifierSource = "usda" | "cnf";

/** The result of resolving one ingredient. */
export interface ResolutionResult {
  outcome: ResolutionOutcome;
  /** The canonical key that was looked up. */
  key: string;
  /** The market that was asked for. */
  market: Market;
  /** The identifier, when there is one. */
  id?: string;
  /** Which source the identifier belongs to. */
  source?: IdentifierSource;
  /** The market the identifier actually came from. */
  source_market?: Market;
  /**
   * True when the identifier came from another market than the one that was
   * asked for. A caller that shows the result has to say so.
   */
  cross_market: boolean;
  /** Every identifier that was tried, in order. */
  attempted: string[];
  /** The alias chain that was followed, when the key was an alias. */
  via?: string[];
  /** Why it could not be resolved. */
  reason?: string;
}

/** One ingredient of a composition, and what became of it. */
export interface ResolvedPart {
  key: string;
  /** The identifier the part resolved to. */
  id?: string;
  /** The grams, exactly as the recipe states them. */
  grams: number;
  /** The result for this part. */
  result: ResolutionResult;
}

/** The result of resolving a whole composition, such as a recipe. */
export interface CompositionResolution {
  outcome: ResolutionOutcome;
  /** The parts that resolved, with their grams untouched. */
  parts: ResolvedPart[];
  /** The parts that did not resolve. */
  missing: { key: string; attempted: string[]; reason?: string }[];
  /**
   * True only when every part resolved. A composition that is not complete
   * must not be presented as a complete recipe, and this flag is how a
   * caller knows.
   */
  complete: boolean;
  /** The market that was asked for. */
  market: Market;
  /** The markets any fallback came from, labelled explicitly. */
  fallbacks: { key: string; id: string; source_market: Market; source: IdentifierSource }[];
  /** Why the composition is not a complete recipe, when it is not. */
  reason?: string;
}

/** A problem found in a registry. */
export interface RegistryProblem {
  kind:
    | "missing-id"
    | "unreviewed-mapping"
    | "missing-evidence"
    | "duplicate-key"
    | "unknown-alias"
    | "cyclic-alias"
    | "conflicting-id"
    | "market-source-mismatch"
    | "unsupported-market"
    | "not-approved"
    | "malformed-entry";
  /** The key the problem concerns, when it concerns one. */
  key?: string;
  /** What is wrong, in plain words. */
  detail: string;
}

let cached: AliasRegistry | null = null;

/** The registry, read from the generated file. */
export function aliasRegistry(): AliasRegistry {
  if (!cached) {
    cached = require("../data/ingredient-aliases.json") as AliasRegistry;
  }
  return cached;
}

/**
 * The source an identifier belongs to, from its namespace.
 *
 * The namespace has to be one the app knows, and the identifier has to be
 * **complete and well formed**: `usda:` with nothing after it is not an
 * identifier, `usda:12a` is not a number, and a namespace the app does not
 * use is not a namespace.
 */
export function sourceOf(id: string): IdentifierSource | null {
  const match = /^(usda|cnf):(\d+)$/.exec(id ?? "");
  if (!match) return null;
  return match[1] as IdentifierSource;
}

/**
 * Which source a market's numbers may come from.
 *
 * The United States catalogue is a United States catalogue, and the Canadian
 * Nutrient File is a Canadian one. A mapping that puts a United States
 * identifier under a Canadian market is not a Canadian mapping: it is a
 * United States record that has not been labelled as one, so it is refused.
 * A United States record used for a Canadian request has to be an
 * explicitly labelled cross-market fallback.
 *
 * The table is the whole of what is allowed. **Extending it is a separate,
 * reviewed decision**: a new row says that a market's numbers may come from a
 * new source, and it is made deliberately, not by a data change.
 */
export const MARKET_SOURCES: Record<string, IdentifierSource> = {
  US: "usda",
  CA: "cnf",
};

/**
 * Check a registry.
 *
 * The problems are returned rather than thrown, so a caller can report all of
 * them at once. An empty list means the registry can be used.
 */
export function validateRegistry(registry: AliasRegistry): RegistryProblem[] {
  const problems: RegistryProblem[] = [];
  if (!registry || !Array.isArray(registry.ingredients)) {
    problems.push({ kind: "malformed-entry", detail: "the registry is malformed: it has no list of ingredients" });
    return problems;
  }
  const byKey = new Map<string, AliasEntry>();
  const claimed = new Map<string, string>();
  const notApproved = new Set((registry.not_approved ?? []).map((entry) => entry.id));
  const defaultMarket = registry.default_market;

  for (const entry of registry.ingredients) {
    if (!entry || typeof entry.key !== "string" || !entry.key.startsWith("ingredient:"))
      problems.push({ kind: "malformed-entry", detail: `an entry has no canonical key: ${JSON.stringify(entry)}` });
    if (!entry?.name?.trim())
      problems.push({ kind: "malformed-entry", key: entry?.key, detail: "the entry has no name" });

    if (entry?.key) {
      if (byKey.has(entry.key))
        problems.push({ kind: "duplicate-key", key: entry.key, detail: "the key appears twice in the registry" });
      else byKey.set(entry.key, entry);
    }

    for (const [market, id] of Object.entries(entry?.ids ?? {})) {
      if (!id) {
        problems.push({ kind: "missing-id", key: entry?.key, detail: `the ${market} mapping is empty` });
        continue;
      }
      const source = sourceOf(id);
      if (!source)
        problems.push({
          kind: "malformed-entry",
          key: entry?.key,
          detail: `the ${market} identifier ${id} is not a well-formed identifier in a known namespace`,
        });
      else {
        // The market's numbers have to come from that market's own source.
        const allowed = MARKET_SOURCES[market];
        if (!allowed)
          problems.push({
            kind: "unsupported-market",
            key: entry?.key,
            detail: `the market ${market} is not one the app maps, so it has no allowed source`,
          });
        else if (allowed !== source)
          problems.push({
            kind: "market-source-mismatch",
            key: entry?.key,
            detail: `the ${market} identifier ${id} is a ${source} identifier, but the ${market} market uses ${allowed} identifiers`,
          });
      }
      if (notApproved.has(id))
        problems.push({
          kind: "not-approved",
          key: entry?.key,
          detail: `the ${market} identifier ${id} was reviewed and is not approved for use`,
        });
      // A mapping that has not been reviewed is an arbitrary string, and the
      // resolution refuses it. It is a problem in the registry too.
      if (!entry?.reviewed?.[market])
        problems.push({
          kind: "unreviewed-mapping",
          key: entry?.key,
          detail: `the ${market} mapping has not been reviewed, so it is not a reviewed mapping`,
        });
      // A mapping to another market needs the evidence a reviewer read, not
      // only a date.
      if (market !== defaultMarket && !entry?.evidence?.[market]?.trim())
        problems.push({
          kind: "missing-evidence",
          key: entry?.key,
          detail: `the ${market} mapping has no evidence of the review, so it is not a reviewed mapping`,
        });
      // One identifier may not serve two different ingredients in one market.
      const claim = `${market}:${id}`;
      const owner = claimed.get(claim);
      if (owner && owner !== entry.key)
        problems.push({
          kind: "conflicting-id",
          key: entry?.key,
          detail: `the ${market} identifier ${id} is also claimed by ${owner}`,
        });
      else if (!owner) claimed.set(claim, entry.key);
    }
  }

  // Alias chains must end, and must end at an entry that exists.
  for (const entry of registry.ingredients ?? []) {
    if (!entry?.alias_of) continue;
    const seen = new Set<string>([entry.key]);
    let next: string | undefined = entry.alias_of;
    while (next) {
      if (seen.has(next)) {
        problems.push({
          kind: "cyclic-alias",
          key: entry.key,
          detail: `the alias chain from ${entry.key} loops back to ${next}`,
        });
        break;
      }
      seen.add(next);
      const target = byKey.get(next);
      if (!target) {
        problems.push({
          kind: "unknown-alias",
          key: entry.key,
          detail: `the alias points at ${next}, which is not in the registry`,
        });
        break;
      }
      next = target.alias_of;
    }
  }

  return problems;
}

/**
 * The problems in a registry, validated once for the registry the app ships
 * and on every call for a registry that was passed in.
 *
 * The static registry is a file that does not change while the app is
 * running, so its validation is cached. A registry that was handed in is
 * validated every time, because it may be a test fixture, and a fixture that
 * is changed between two calls must be seen as it is now.
 */
let staticProblems: RegistryProblem[] | null = null;

export function registryProblems(registry: AliasRegistry): RegistryProblem[] {
  if (registry === aliasRegistry()) {
    if (!staticProblems) staticProblems = validateRegistry(registry);
    return staticProblems;
  }
  return validateRegistry(registry);
}

/**
 * Resolve one ingredient in one market.
 *
 * **The resolution is fail-closed.** It does not rely on the caller having
 * run the validation: the registry is checked here, and every rule the
 * validation makes is made again at the point of use, so a registry that has
 * not been validated still cannot produce an identifier the rules forbid.
 *
 *   - an invalid registry resolves to nothing at all, and says why;
 *   - a mapping that has not been reviewed is not used;
 *   - a mapping to another market needs the evidence a reviewer read;
 *   - an identifier in a namespace the app does not know is not used;
 *   - a market's numbers have to come from that market's own source, so a
 *     United States identifier under a Canadian market is refused rather
 *     than passed off as a Canadian one;
 *   - an identifier that was reviewed and refused is not used;
 *   - an alias chain that loops, or that points at nothing, resolves to
 *     nothing;
 *   - a Canadian record's cross-reference is never proof of equivalence: the
 *     resolution only ever uses an identifier the registry maps explicitly.
 *
 * A market with no approved mapping falls back to the default market, and
 * the result says so: `cross_market` is true and `source_market` names the
 * market the identifier actually came from. A caller that shows a fallback
 * has to label it, because the numbers come from a different country's
 * food.
 */
export function resolveIngredient(key: string, market: Market, registry = aliasRegistry()): ResolutionResult {
  const failed = (reason: string, attempted: string[] = []): ResolutionResult => ({
    outcome: "unavailable",
    key,
    market,
    cross_market: false,
    attempted,
    reason,
  });

  // The whole registry is checked, not only the entry that was asked for: a
  // registry that is invalid cannot produce an apparently valid result.
  const problems = registryProblems(registry);
  if (problems.length)
    return failed(`the registry is invalid, so nothing resolves: ${problems[0].detail}`);

  const byKey = new Map<string, AliasEntry>();
  for (const entry of registry.ingredients) {
    if (!entry || typeof entry.key !== "string") continue;
    if (!byKey.has(entry.key)) byKey.set(entry.key, entry);
  }

  const entry = byKey.get(key);
  if (!entry) return failed(`there is no ingredient with the key ${key}`);

  // Follow the alias chain, refusing to follow it for ever.
  const attempted: string[] = [];
  const via: string[] = [entry.key];
  const seen = new Set<string>([entry.key]);
  let target = entry;
  while (target.alias_of) {
    if (seen.has(target.alias_of))
      return failed(`the alias chain from ${key} loops back to ${target.alias_of}`, attempted);
    seen.add(target.alias_of);
    const next = byKey.get(target.alias_of);
    if (!next) return failed(`the alias points at ${target.alias_of}, which is not in the registry`, attempted);
    via.push(next.key);
    target = next;
  }

  const notApproved = new Set((registry.not_approved ?? []).map((entry) => entry.id));
  const check = (id: string, reviewDate: string | undefined, marketCode: string): string | null => {
    if (!id) return "the mapping has no identifier";
    if (!reviewDate) return "the mapping has not been reviewed, so it is not used";
    const source = sourceOf(id);
    if (!source) return `the identifier ${id} is not a well-formed identifier in a known namespace`;
    const allowed = MARKET_SOURCES[marketCode];
    if (!allowed) return `the market ${marketCode} is not one the app maps`;
    if (allowed !== source)
      return `the identifier ${id} is a ${source} identifier, but the ${marketCode} market uses ${allowed} identifiers`;
    if (notApproved.has(id)) return `the identifier ${id} was reviewed and is not approved for use`;
    if (marketCode !== registry.default_market && !target.evidence?.[marketCode]?.trim())
      return `the ${marketCode} mapping has no evidence of the review, so it is not used`;
    return null;
  };

  const direct = target.ids?.[market];
  if (direct !== undefined) {
    attempted.push(direct);
    const problem = check(direct, target.reviewed?.[market], market);
    if (problem) return failed(problem, attempted);
    return {
      outcome: "resolved",
      key,
      market,
      id: direct,
      source: sourceOf(direct) ?? undefined,
      source_market: market,
      cross_market: false,
      attempted,
      via: via.length > 1 ? via : undefined,
    };
  }

  const fallback = target.ids?.[registry.default_market];
  if (fallback !== undefined) {
    attempted.push(fallback);
    const problem = check(fallback, target.reviewed?.[registry.default_market], registry.default_market);
    if (problem) return failed(problem, attempted);
    return {
      outcome: "fallback",
      key,
      market,
      id: fallback,
      source: sourceOf(fallback) ?? undefined,
      source_market: registry.default_market,
      cross_market: true,
      attempted,
      via: via.length > 1 ? via : undefined,
      reason: `there is no approved ${market} equivalent; the ${registry.default_market} one was used`,
    };
  }

  return failed(
    `the ingredient is in the registry but has no identifier in ${market} or in ${registry.default_market}`,
    attempted,
  );
}

/**
 * Resolve a whole composition.
 *
 * Every part keeps its grams exactly as the recipe states them. A part that
 * does not resolve is **not** dropped and **not** counted as zero: the
 * composition comes back incomplete, with the missing parts named, so the
 * caller can say the recipe is incomplete instead of serving a different
 * food under the same name.
 *
 * The outcome says exactly what happened:
 *
 *   resolved    every ingredient resolved in the market that was asked for.
 *   fallback    every ingredient resolved, but at least one of them came
 *               from another market, and the result says which.
 *   incomplete  some ingredients resolved and one or more did not.
 *   unavailable none of the required ingredients resolved.
 *
 * A composition with no ingredients at all is **not** a complete recipe, so
 * it comes back unavailable rather than resolved.
 */
export function resolveComposition(
  parts: { key: string; grams: number }[],
  market: Market,
  registry = aliasRegistry(),
): CompositionResolution {
  const resolved: ResolvedPart[] = [];
  const missing: CompositionResolution["missing"] = [];
  const fallbacks: CompositionResolution["fallbacks"] = [];

  if (!parts.length)
    return {
      outcome: "unavailable",
      parts: [],
      missing: [],
      complete: false,
      market,
      fallbacks: [],
      reason: "the composition has no ingredients, so it is not a recipe",
    };

  let direct = 0;
  for (const part of parts) {
    const result = resolveIngredient(part.key, market, registry);
    resolved.push({ key: part.key, id: result.id, grams: part.grams, result });
    if (result.outcome === "resolved") {
      direct += 1;
      continue;
    }
    if (result.outcome === "fallback") {
      if (result.id && result.source_market && result.source)
        fallbacks.push({
          key: part.key,
          id: result.id,
          source_market: result.source_market,
          source: result.source,
        });
      continue;
    }
    missing.push({ key: part.key, attempted: result.attempted, reason: result.reason });
  }

  const outcome: ResolutionOutcome =
    missing.length === parts.length
      ? "unavailable"
      : missing.length
        ? "incomplete"
        : fallbacks.length
          ? "fallback"
          : "resolved";

  return {
    outcome,
    parts: resolved,
    missing,
    complete: missing.length === 0 && direct + fallbacks.length === parts.length,
    market,
    fallbacks,
    reason:
      outcome === "unavailable" && !missing.length
        ? "none of the ingredients could be resolved"
        : outcome === "incomplete"
          ? `${missing.length} of ${parts.length} ingredients could not be resolved`
          : undefined,
  };
}
